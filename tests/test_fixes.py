def test_a_finding_pointing_at_the_wrong_field_offers_nothing(
    tmp_path: Path, name: str, rule: str
) -> None:
    """Totality, one guard deeper: the rule is right and the path is not.

    The shallow version — a finding with no field path at all — is above. This
    one walks each producer past its first guard and into the ones that read the
    document, which is where a stale finding from a tree that has moved lands.
    """
    root = fixture_tree(tmp_path, name)
    inventory = load_tree(root)
    finding = next(entry for entry in validate(inventory) if entry.rule == rule)
    assert fixes_for(finding, inventory), "the fixture must produce a repairable finding"
    for path in (
        ("spec", "interfaces", 99, "mac"),
        ("spec", "interfaces", "x", "vlan"),
        ("spec", "views", "l1", "nodes"),
        ("spec", "vrfs", "x"),
        ("spec", "members", 99),
        ("spec", "elsewhere"),
    ):
        assert fixes_for(replace(finding, field_path=path), inventory) == (), path


