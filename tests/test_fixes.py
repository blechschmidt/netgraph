def test_a_repair_that_fails_halfway_leaves_no_trace_of_its_first_half(
    fixable: Path,
) -> None:
    """A batch is atomic per operation; a *repair* has to be atomic as a whole."""
    inventory = load_tree(fixable)
    finding = next(entry for entry in validate(inventory) if entry.rule == "W113")
    (declare,) = fixes_for(finding, inventory)
    broken = Fix(
        declare.key,
        declare.title,
        (declare.operations[0], UnsetField(address="sw-a", path="spec.nothing")),
    )
    session = EditSession(root=fixable)
    with pytest.raises(EditError):
        apply_fix(session, finding, broken)
    assert session.changes == {}


