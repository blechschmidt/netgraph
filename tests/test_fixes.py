def test_a_repair_that_would_make_things_worse_is_rolled_back(tmp_path: Path) -> None:
    """Removing the cable is a real repair, and here it orphans a device."""
    root = tmp_path / "orphan"
    root.mkdir()
    text = _documents(
        _switch("sw-a", ["port1"]),
        _computer("pc-a"),
        _cable("cbl-1", "sw-a:missing", "pc-a:eno1"),
    )
    (root / "net.yaml").write_text(text, encoding="utf-8")

    session = EditSession(root=root)
    report = repair(session, choices={"E001": "remove"})
    assert report.applied == ()
    assert {entry.finding.rule for entry in report.skipped} == {"E001"}
    assert "W103" in " ".join(str(finding) for finding in report.skipped[0].introduced)
    # Rolled back to the byte: the session has nothing pending, so nothing is
    # written and no file shows an empty diff.
    assert session.changes == {}
    assert report.diff == ""
    assert (root / "net.yaml").read_text(encoding="utf-8") == text


