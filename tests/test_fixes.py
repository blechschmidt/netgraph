@given(
    plan=ng.inventory_plans(),
    stale=st.lists(st.sampled_from(["ghost-a", "ghost-b"]), min_size=1, max_size=2),
)
@settings(
    # Each example writes a tree, validates it three times over and writes it
    # again, so this is one of the properties that is capped in absolute terms
    # as well as by the profile. See ``capped()`` in tests/test_properties.py.
    max_examples=capped(50),
    deadline=None,
    suppress_health_check=[HealthCheck.too_slow, HealthCheck.function_scoped_fixture],
)
def test_a_fix_never_introduces_a_finding(
    tmp_path_factory: pytest.TempPathFactory, plan: ng.InventoryPlan, stale: list[str]
) -> None:
    """The invariant, on generated inventories spoiled with a fixable defect.

    A generated inventory is *valid*, so on its own it would exercise the loop's
    empty path and nothing else. Adding a layout document that places elements
    nobody declared guarantees at least one repair per run, and leaves whatever
    findings the generator happened to produce to be quantified over as well.
    """
    root = plan.write(tmp_path_factory.mktemp("fixes"))
    (root / "layout.yaml").write_text(
        _layout({name: [index * 10, 0] for index, name in enumerate(dict.fromkeys(stale))}),
        encoding="utf-8",
    )
    inventory = load_tree(root)
    assume(not inventory.errors)
    before = counts(validate(inventory))

    session = EditSession(root=root)
    report = repair(session)
    assert report.applied, "the stale geometry must have been repaired"
    if report.changed:
        session.commit()

    after = validate(load_tree(root))
    for rule, count in counts(after).items():
        assert count <= before[rule], f"{rule} went from {before[rule]} to {count}"
    standing = identities(after)
    for entry in report.applied:
        assert (entry.finding.rule, entry.finding.message) not in standing


