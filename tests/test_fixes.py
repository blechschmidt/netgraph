"""One-click repairs: what each producer offers, and the promise none may break.

Three layers are asserted here, and the third is the one the feature stands on:

**What a producer offers.** One test per fixable rule, on the fixture that
provokes it, checking the operations and — for a rule with more than one reading
— that both are offered and neither is chosen.

**What the loop does with them.** ``repair`` applies one fix at a time against
the tree the previous one left, so two findings in one document do not undo each
other, and a repair that would make things worse is rolled back to the byte.

**The invariant.** *A fix never introduces a finding.* Asserted by re-validating
after every repair — over the example inventories, over every fixture in
``tests/fixtures/``, and over inventories nobody wrote, generated by the
Hypothesis strategies in ``tests/strategies.py`` and deliberately spoiled with a
defect a producer can see.
"""

