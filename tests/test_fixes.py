def capped(limit: int) -> int:
    """At most ``limit`` examples, and fewer when the profile asks for fewer."""
    return min(int(settings().max_examples), limit)


def copy_tree(source: Path, destination: Path) -> Path:
    """Copy an inventory (or a single fixture file) into a writable directory."""
    destination.mkdir(parents=True, exist_ok=True)
    sources = [source] if source.is_file() else sorted(source.rglob("*"))
    for path in sources:
        if not path.is_file() or path.suffix.lower() not in (".yaml", ".yml"):
            continue
        relative = path.name if source.is_file() else path.relative_to(source).as_posix()
        target = destination / relative
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_bytes(path.read_bytes())
    return destination


def findings_of(root: Path) -> list[Finding]:
    return validate(load_tree(root))


def counts(findings: Sequence[Finding]) -> Counter[str]:
    return Counter(finding.rule for finding in findings)


def identities(findings: Sequence[Finding]) -> set[tuple[str, str]]:
    return {(finding.rule, finding.message) for finding in findings}


def offers_in(root: Path, rule: str) -> tuple[Fix, ...]:
    """Every repair offered for the first ``rule`` finding of the tree at ``root``."""
    inventory = load_tree(root)
    for finding in validate(inventory):
        if finding.rule == rule:
            return fixes_for(finding, inventory)
    raise AssertionError(f"no {rule} finding in {root}")


def repaired(root: Path, **kwargs: Any) -> Any:
    """Run the repair loop over ``root`` and commit what it kept."""
    session = EditSession(root=root)
    report = repair(session, **kwargs)
    if report.changed:
        session.commit()
    return report


